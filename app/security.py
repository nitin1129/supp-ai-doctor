def is_valid_aadhaar(number: str) -> bool:
    if not re.fullmatch(r"[2-9]\d{11}", number):
        return False
    c = 0
    for i, ch in enumerate(reversed(number)):
        c = _VERHOEFF_D[c][_VERHOEFF_P[i % 8][int(ch)]]
    return c == 0


def mask(value: str | None, keep: int = 4) -> str | None:
    if not value:
        return None
    return "X" * max(len(value) - keep, 0) + value[-keep:]
